const glossary: Record<Lang, readonly (readonly [string, string])[]> = {
  zh: [["这台 Mac", "这台电脑"], ["废纸篓", "回收站"], ["访达", "文件资源管理器"], ["Finder", "文件资源管理器"], ["macOS", "Windows"], ["系统设置", "Windows 设置"]],
  en: [["this Mac", "this PC"], ["Trash", "Recycle Bin"], ["Finder", "File Explorer"], ["macOS", "Windows"], ["System Settings", "Windows Settings"]],
};
for (const lang of ["zh", "en"] as const) glossary[lang] = [...glossary[lang]].sort((a, b) => b[0].length - a[0].length);

const STORAGE_KEY = "cleanzo.lang";
let sessionPref: LangPref | undefined;
let nativeLocale: string | undefined;

export function setNativeLocale(locale: string) {
  nativeLocale = locale;
}

export function getPref(): LangPref {
  if (sessionPref !== undefined) return sessionPref;
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === "zh" || v === "en") return v;
  } catch {
    /* ignore */
  }
  return "system";
}

export function setPref(p: LangPref) {
  sessionPref = p;
  try {
    localStorage.setItem(STORAGE_KEY, p);
  } catch {
    /* ignore */
  }
}

function resolveLang(): Lang {
  const pref = getPref();
  if (pref !== "system") return pref;
  if (nativeLocale) return nativeLocale.toLowerCase().startsWith("zh") ? "zh" : "en";
  try {
    return (navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en";
  } catch {
    return "en";
  }
}

export function currentLang(): Lang {
  return resolveLang();
}

/** 规则未知时保留稳定 ID。 */
export function ruleName(id: string): string {
  const key = `rule.${id}.name` as keyof (typeof dict)["zh"];
  return key in dict.zh ? t(key) : id;
}

export function ruleDesc(id: string): string {
  const key = `rule.${id}.desc` as keyof (typeof dict)["zh"];
  return key in dict.zh ? t(key) : id;
}

/** t(key, vars) returns the localized string for the current language. */
export function t(key: keyof (typeof dict)["zh"] & keyof (typeof dict)["en"], vars?: Record<string, string | number>): string {
  const lang = resolveLang();
  const messages: Readonly<Record<string, string>> = dict[lang];
  const fallback: Readonly<Record<string, string>> = dict.en;
  let s = (isWindows() ? messages[`${key}@win`] ?? fallback[`${key}@win`] : undefined) ?? messages[key] ?? fallback[key] ?? key;
  if (isWindows()) for (const [from, to] of glossary[lang]) s = s.replaceAll(from, to);
  if (vars) {
    // Plural token {n|one/other}: English picks "one" only for exactly 1.
    // Chinese strings carry their own counters (项/个/天) and never use it.
    s = s.replace(/\{(\w+)\|([^{}/]+)\/([^{}]+)\}/g, (m, k: string, one: string, other: string) =>
      k in vars && lang === "en" && Number(vars[k]) === 1 ? one : other,
    );
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

/** 是否有内置名称翻译。 */
export function isBuiltinCategory(name: string): boolean {
  return Object.hasOwn(dict.zh, `name.${name}`);
}

/** categoryName maps a built-in category name to its localized title. */
export function categoryName(name: string): string {
  const key = `name.${name}` as keyof (typeof dict)["zh"];
  if (key in dict.zh) return t(key);
  return name;
}

/** categoryDescription maps a built-in category name to its localized description. */
export function categoryDescription(name: string, fallback: string): string {
  const key = `desc.${name}` as keyof (typeof dict)["zh"];
  if (key in dict.zh) return t(key);
  return fallback;
}

/** kindLabel maps a Go uninstall kind key to a localized label. */
export function kindLabel(kind: string): string {
  const key = `kind.${kind}` as keyof (typeof dict)["zh"];
  if (key in dict.zh) return t(key);
  return kind;
}
